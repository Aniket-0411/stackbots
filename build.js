#!/usr/bin/env node
/* STACKBOTS build — node build.js [--strict]
 * Concatenates src/*.js + generated level data into:
 *   dist/stackbots.html  (standalone document)
 *   dist/artifact.html   (same page without doctype/html/head/body wrappers, starts with <title>)
 * Node built-ins only. */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const STRICT = process.argv.includes('--strict');
const FONT_LINK = '<link href="https://fonts.googleapis.com/css2?family=Bungee&family=Nunito:wght@600;700;800;900&display=swap" rel="stylesheet">';
const JS_ORDER = ['engine.js', 'levels.js', 'audio.js', 'input.js', 'render.js', 'net.js', 'ui.js', 'main.js'];

let warnings = 0;
function warn(msg) { warnings++; console.warn('WARN  ' + msg); }
function read(p) { return fs.readFileSync(p, 'utf8'); }

// ---------- levels ----------
function loadWorlds() {
  const worlds = [];
  for (let n = 1; n <= 10; n++) {
    const f = path.join(ROOT, 'levels', 'world' + String(n).padStart(2, '0') + '.json');
    if (!fs.existsSync(f)) continue;
    let w;
    try { w = JSON.parse(read(f)); } catch (e) { warn(path.basename(f) + ': invalid JSON (' + e.message + ') — skipped'); continue; }
    if (!w || !Array.isArray(w.levels)) { warn(path.basename(f) + ': no "levels" array — skipped'); continue; }
    worlds.push({ world: w.world || n, name: w.name || ('World ' + n), theme: w.theme || 'meadow', levels: w.levels, file: path.basename(f) });
  }
  if (!worlds.length) {
    const f = path.join(ROOT, 'levels', '_examples.json');
    const w = JSON.parse(read(f));
    worlds.push({ world: w.world || 0, name: w.name || 'Examples', theme: w.theme || 'meadow', levels: w.levels, file: '_examples.json' });
    console.log('info  no levels/worldNN.json yet — using levels/_examples.json');
  }
  return worlds;
}

function stripLevel(lv) {
  // keep only fields the game uses; preserve unknown entity fields (engine may read them)
  const o = {};
  for (const k of ['id', 'name', 'hint', 'minPlayers', 'tether', 'tetherLength', 'map', 'entities']) if (lv[k] !== undefined) o[k] = lv[k];
  for (const k of Object.keys(lv)) if (!(k in o) && !/^_|^comment|^notes?$/i.test(k)) o[k] = lv[k];
  return o;
}

function genLevelsJs(worlds) {
  const data = worlds.map(w => ({ world: w.world, name: w.name, theme: w.theme, levels: w.levels.map(stripLevel) }));
  const json = JSON.stringify(data).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  return '/* GENERATED by build.js from levels/*.json — do not edit by hand */\n' +
    '(function () { var SB = globalThis.SB = globalThis.SB || {}; SB.LEVEL_DATA = ' + json + '; })();\n';
}

function loadEngine(p) {
  try {
    delete require.cache[require.resolve(p)];
    const mod = require(p);
    const E = (mod && mod.parseLevel) ? mod : (globalThis.SB && globalThis.SB.Engine);
    const need = ['parseLevel', 'createWorld', 'reset', 'step', 'snapshot', 'applySnapshot', 'tileAt', 'isSolidFor'];
    const missing = E ? need.filter(k => typeof E[k] !== 'function') : need;
    return { E, missing };
  } catch (e) { return { E: null, missing: ['(load error: ' + e.message + ')'] }; }
}

function validateWithEngine(Engine, worlds) {
  if (!Engine || !Engine.parseLevel) { warn('engine has no parseLevel — skipped validation'); return; }
  let ok = 0, bad = 0, idx = 0;
  for (const w of worlds) {
    for (const lv of w.levels) {
      try {
        const L = Engine.parseLevel(lv, { world: w.world, theme: w.theme, worldName: w.name, index: idx });
        if (Engine.createWorld) {
          const W = Engine.createWorld(L, { slots: [0, 1, 2, 3] });
          if (Engine.snapshot) {
            const n = Buffer.byteLength(JSON.stringify(Engine.snapshot(W)));
            if (n > 3000) warn((lv.id || '?') + ': initial snapshot is ' + n + ' bytes (> 3000)');
          }
        }
        ok++;
      } catch (e) { bad++; warn(w.file + ' level ' + (lv.id || idx) + ': ' + e.message); }
      idx++;
    }
  }
  console.log('info  engine validation: ' + ok + ' ok, ' + bad + ' failed');
}

// ---------- assemble ----------
function main() {
  fs.mkdirSync(DIST, { recursive: true });
  const worlds = loadWorlds();
  const levelsJs = genLevelsJs(worlds);
  fs.writeFileSync(path.join(SRC, 'levels.js'), levelsJs);
  const nLevels = worlds.reduce((a, w) => a + w.levels.length, 0);
  console.log('info  levels: ' + worlds.map(w => w.file + '(' + w.levels.length + ')').join(', ') + ' = ' + nLevels);

  let enginePath = path.join(SRC, 'engine.js');
  let usingStub = false, why = '';
  if (!fs.existsSync(enginePath)) why = 'src/engine.js not found';
  else {
    const r = loadEngine(enginePath);
    if (r.missing.length) why = 'src/engine.js incomplete (missing ' + r.missing.join(', ') + ')';
    else validateWithEngine(r.E, worlds);
  }
  if (why) {
    enginePath = path.join(ROOT, 'test', 'fakes', 'engine-stub.js');
    usingStub = true;
    warn(why + ' — building with THROWAWAY test/fakes/engine-stub.js');
    if (STRICT) { console.error('ERROR --strict: real engine required'); process.exit(1); }
  }

  const parts = [];
  for (const f of JS_ORDER) {
    const p = f === 'engine.js' ? enginePath : path.join(SRC, f);
    if (!fs.existsSync(p)) { console.error('ERROR missing ' + p); process.exit(1); }
    let code = f === 'levels.js' ? levelsJs : read(p);
    if (/<\/script/i.test(code) || /<!--/.test(code)) {
      if (f === 'levels.js') code = code.replace(/<\//g, '<\\/');
      else { console.error('ERROR ' + f + ' contains "</script" or "<!--" which would break the inline <script>'); process.exit(1); }
    }
    parts.push('/* ===== ' + f + (f === 'engine.js' && usingStub ? ' (STUB)' : '') + ' ===== */\n' + code.trim() + '\n');
  }
  let js = parts.join('\n');
  const css = read(path.join(SRC, 'style.css')).trim();
  const body = read(path.join(SRC, 'template.html')).trim();
  const hash = crypto.createHash('sha1').update(js).update(css).update(body).digest('hex').slice(0, 10);
  const buildInfo = '(function(){var SB=globalThis.SB=globalThis.SB||{};SB.BUILD={hash:' + JSON.stringify(hash) +
    ',levels:' + nLevels + ',stub:' + usingStub + '};})();\n';
  js = buildInfo + js;

  const common = '<title>Stackbots</title>\n' + FONT_LINK + '\n<style>\n' + css + '\n</style>\n';
  const tail = body + '\n<script>\n' + js + '</script>\n';
  const standalone = '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n' +
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' +
    '<meta name="theme-color" content="#1B1530">\n' + common + '</head>\n<body>\n' + tail + '</body>\n</html>\n';
  const artifact = common + tail;

  fs.writeFileSync(path.join(DIST, 'stackbots.html'), standalone);
  fs.writeFileSync(path.join(DIST, 'artifact.html'), artifact);
  const kb = n => (n / 1024).toFixed(1) + ' KiB';
  console.log('built dist/stackbots.html ' + kb(Buffer.byteLength(standalone)) + ', dist/artifact.html ' + kb(Buffer.byteLength(artifact)) +
    ' (build ' + hash + (usingStub ? ', ENGINE STUB' : '') + ')' + (warnings ? ' — ' + warnings + ' warning(s)' : ''));
  if (Buffer.byteLength(standalone) > 1024 * 1024) { console.error('ERROR output exceeds 1 MB'); process.exit(1); }
  if (STRICT && warnings) process.exit(1);
}

main();
